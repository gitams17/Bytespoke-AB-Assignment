-- =============================================================================
-- Script  : 02_create_dimensions.sql
-- Purpose : Create all dimension tables for the bank transaction mart.
-- Schema  : Star schema dimensions
-- SCD     : Type 1 (last-write-wins) for customer and account — justified by
--           internship scope; history is not a stated requirement.
-- =============================================================================

-- ---------------------------------------------------------------------------
-- dim_date — pre-populated calendar dimension
-- One row per calendar day; generated by Python for the required date range.
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS dim_date (
    date_key        INTEGER PRIMARY KEY,   -- YYYYMMDD integer surrogate key
    full_date       DATE NOT NULL UNIQUE,
    year            INTEGER NOT NULL,
    quarter         INTEGER NOT NULL,      -- 1–4
    month           INTEGER NOT NULL,      -- 1–12
    month_name      VARCHAR NOT NULL,
    week_of_year    INTEGER NOT NULL,      -- ISO week
    day_of_month    INTEGER NOT NULL,      -- 1–31
    day_of_week     INTEGER NOT NULL,      -- 1=Monday … 7=Sunday (ISO)
    day_name        VARCHAR NOT NULL,
    is_weekend      BOOLEAN NOT NULL,
    is_month_start  BOOLEAN NOT NULL,
    is_month_end    BOOLEAN NOT NULL
);

-- ---------------------------------------------------------------------------
-- dim_customer — one row per unique customer (Type 1 SCD)
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS dim_customer (
    customer_key        INTEGER PRIMARY KEY,   -- surrogate key
    customer_id         VARCHAR NOT NULL UNIQUE,  -- natural / business key
    full_name           VARCHAR NOT NULL,
    email               VARCHAR,
    phone               VARCHAR,
    country             VARCHAR,
    customer_segment    VARCHAR,               -- e.g., RETAIL, SME, CORPORATE
    risk_rating         VARCHAR,               -- LOW, MEDIUM, HIGH
    onboarded_date      DATE,
    is_active           BOOLEAN DEFAULT TRUE,
    updated_at          TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- ---------------------------------------------------------------------------
-- dim_account — one row per unique account (Type 1 SCD)
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS dim_account (
    account_key         INTEGER PRIMARY KEY,   -- surrogate key
    account_id          VARCHAR NOT NULL UNIQUE,  -- natural / business key
    customer_key        INTEGER NOT NULL,              -- logical FK to dim_customer; integrity checked via DQ-03
    account_type        VARCHAR NOT NULL,      -- CHECKING, SAVINGS, CREDIT, LOAN
    currency            VARCHAR NOT NULL,      -- ISO 4217 e.g. USD
    opened_date         DATE,
    is_active           BOOLEAN DEFAULT TRUE,
    credit_limit        DECIMAL(18, 2),        -- NULL for non-credit accounts
    updated_at          TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- ---------------------------------------------------------------------------
-- dim_transaction_type — small stable dimension (Type 0 — never changes)
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS dim_transaction_type (
    transaction_type_key INTEGER PRIMARY KEY,
    type_code            VARCHAR NOT NULL UNIQUE,  -- PURCHASE, TRANSFER, etc.
    type_label           VARCHAR NOT NULL,
    type_category        VARCHAR NOT NULL,          -- DEBIT or CREDIT
    description          VARCHAR
);

